import { PrismaClient } from "@prisma/client";

const globalForPrisma = globalThis as unknown as {
  prisma: PrismaClient | undefined;
};

function createPrismaClient() {
  return new PrismaClient({
    log: process.env.NODE_ENV === "development" ? ["error", "warn"] : ["error"],
  });
}

function getPrisma() {
  const existing = globalForPrisma.prisma;
  // Stale HMR/global cache can miss newly added models (e.g. promoBanner)
  const promoBanner = existing
    ? (existing as unknown as Record<string, { findMany?: unknown }>).promoBanner
    : undefined;
  if (existing && typeof promoBanner?.findMany === "function") {
    return existing;
  }
  const client = createPrismaClient();
  if (process.env.NODE_ENV !== "production") {
    globalForPrisma.prisma = client;
  }
  return client;
}

export const prisma = getPrisma();
